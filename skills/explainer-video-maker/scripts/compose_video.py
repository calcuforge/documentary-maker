def build_parser():
    parser = argparse.ArgumentParser(description="Generate per-scene Remotion composition files.")
    cli_envelope.add_format_arg(parser)
    parser.add_argument("--project", required=True)
    parser.add_argument("--video", required=True)
    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    prefs_path = workspace.prefs_path(args.project)
    if not os.path.isfile(prefs_path):
        cli_envelope.emit_usage_error(
            f"Project prefs not found: {prefs_path} "
            f"(projects resolve under the workspace: {workspace.projects_dir()}; "
            "run from the workspace root or set EXPLAINER_WORKSPACE)",
            fmt=args.format)
    with open(prefs_path, "r", encoding="utf-8") as f:
        prefs = yaml.safe_load(f) or {}
    # Deep-merge theme onto prefs.
    category = prefs.get("project", {}).get("category")
    if category:
        theme_data = themes_mod.show_theme(category)
        if theme_data:
            prefs = themes_mod.resolve_theme(category, prefs_path)

    video_dir = workspace.video_dir(args.project, args.video)
    if not os.path.isdir(video_dir):
        cli_envelope.emit_usage_error(
            f"Video dir not found: {video_dir}", fmt=args.format)

    script_path = os.path.join(video_dir, "narration_script.yaml")
    try:
        script = script_schema.load_script(script_path)
    except script_schema.SchemaError as exc:
        cli_envelope.emit_usage_error(str(exc), fmt=args.format)

    template_abs = _template_path(prefs).replace("\\", "/")
    default_props_json = json.dumps(_default_props(prefs), ensure_ascii=False, indent=2)
    comp_id = _composition_id(prefs)
    fps = str(prefs.get("video", {}).get("fps", 30))
    width, height = _composition_dims(prefs)

    generated = []
    for scene in script["scenes"]:
        name = scene["name"]
        scene_dir = os.path.join(video_dir, "scenes", name)
        os.makedirs(scene_dir, exist_ok=True)

        # composition.json — shot designs for runtime staticFile consumption.
        composition = {
            "scene": {
                "name": name,
                "label": scene.get("label") or name,
                "chapter": scene.get("chapter"),
            },
            "shots": script_schema.effective_shots(scene),
        }
        composition_path = os.path.join(scene_dir, "composition.json")
        with open(composition_path, "w", encoding="utf-8") as f:
            json.dump(composition, f, ensure_ascii=False, indent=2)

        scene_tsx = (SCENE_TSX_TEMPLATE
                     .replace("__TEMPLATE_PATH__", template_abs)
                     .replace("__SCENE_NAME__", name))
        entry_tsx = (ENTRY_TSX_TEMPLATE
                     .replace("__TEMPLATE_PATH__", template_abs)
                     .replace("__SCENE_NAME__", name)
                     .replace("__COMP_ID__", comp_id)
                     .replace("__FPS__", fps)
                     .replace("__WIDTH__", str(width))
                     .replace("__HEIGHT__", str(height))
                     .replace("__DEFAULT_PROPS__", default_props_json))

        scene_tsx_path = os.path.join(scene_dir, "scene.tsx")
        entry_tsx_path = os.path.join(scene_dir, "entry.tsx")
        with open(scene_tsx_path, "w", encoding="utf-8") as f:
            f.write(scene_tsx)
        with open(entry_tsx_path, "w", encoding="utf-8") as f:
            f.write(entry_tsx)

        generated.append({
            "scene": name,
            "scene_tsx": scene_tsx_path,
            "entry_tsx": entry_tsx_path,
            "composition_json": composition_path,
            "shots": [s["name"] for s in composition["shots"]],
        })

    cli_envelope.emit_ok(
        data={
            "scenes": generated,
            "composition_id": comp_id,
            "dimensions": [width, height],
            "default_props": _default_props(prefs),
            "render_hint": (
                'cd "$TEMPLATE_PATH" && npx remotion render '
                '"$VDIR/scenes/<scene>/entry.tsx" '
                f'{comp_id} "$VDIR/scenes/<scene>/scene.mp4" '
                '--public-dir "$VDIR" --video-bitrate 16M'
            ),
        },
        message=f"Generated scene.tsx + entry.tsx for {len(generated)} scene(s).",
        fmt=args.format,
    )


if __name__ == "__main__":
    main()
