#!/usr/bin/env python3
"""Generate per-scene Remotion composition files.

For every scene in narration_script.yaml (chapters → scenes → shots), this
writes three files under `scenes/{scene}/`:

    scene.tsx        — the scene composition: TransitionSeries over shots,
                       audio-master clock compensation, scene narration audio,
                       scene subtitles, shot overlays. Imports components from
                       the shared remotion-video-template (never copied).
    entry.tsx        — Composition registration; calculateMetadata reads the
                       scene's timing.json for durationInFrames.
    composition.json — JSON mirror of the scene's shot designs, read at
                       runtime via staticFile.

Rendering is per scene (each scene → scenes/{scene}/scene.mp4); scenes are
then concatenated losslessly by merge_video.py. --public-dir stays the video
root, so scene files resolve via staticFile("scenes/{scene}/...") and the
assets manifest stays shared at staticFile("assets/manifest.json").

Timing: each scene's timing.json lists `shots` with frame budgets. The scene
composition scales shots proportionally so the rendered total equals
timing.total_frames exactly (TransitionSeries overlap compensation — mirrors
the math from remotion-video-template/src/Video.js).
"""
