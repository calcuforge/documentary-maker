def _template_path(prefs):
    """Resolve the remotion-video-template location.

    Relative paths are resolved against the explainer-video-maker root
    (DOC_ROOT), matching the documented convention: the template sits at
    ../remotion-video-template next to the skill repo root. Absolute paths
    are used as-is.
    """
    rel = prefs.get("paths", {}).get("remotion_template", "../remotion-video-template")
    if os.path.isabs(rel):
        return os.path.normpath(rel)
    return os.path.normpath(os.path.join(DOC_ROOT, rel))


def _composition_id(prefs):
    orientation = prefs.get("project", {}).get("orientation", "horizontal")
    resolution = prefs.get("video", {}).get("resolution", "1080p")
    if orientation == "vertical":
        return "MainVideoVertical"
    if resolution == "4k":
        return "MainVideo4K"
    return "MainVideo"


def _composition_dims(prefs):
    orientation = prefs.get("project", {}).get("orientation", "horizontal")
    resolution = prefs.get("video", {}).get("resolution", "1080p")
    if orientation == "vertical":
        return (1080, 1920)
    if resolution == "4k":
        return (3840, 2160)
    return (1920, 1080)


def _default_props(prefs):
    theme = prefs.get("theme", {})
    return {
        "primaryColor": theme.get("primary_color", "#1a2a3a"),
        "backgroundColor": theme.get("background_color", "#0e1419"),
        "textColor": theme.get("text_color", "#e6e8eb"),
        "accentColor": theme.get("accent_color", "#d4b483"),
        "titleSize": 80,
        "subtitleSize": 40,
        "bodySize": 28,
        # Progress bar is off by default for per-scene rendering: each scene
        # would reset 0→100%, which reads oddly after concatenation. Enable
        # to show in-scene shot-segment progress.
        "showProgressBar": False,
        "progressBarHeight": 65,
        "progressFontSize": 19,
        "progressActiveColor": theme.get("primary_color", "#1a2a3a"),
        "bgmVolume": 0,  # BGM is mixed via FFmpeg after scene merge (Step 10)
        "enableAudio": True,
        # Subtitles are burned in per scene by default (scene-relative SRT).
        "enableSubtitles": True,
        "enableAnimations": True,
        "transitionType": theme.get("transition_type", "fade"),
        "transitionDuration": theme.get("transition_duration", 18),
        "scaleFactor": 2 if prefs.get("video", {}).get("resolution") == "4k" else 1,
        "orientation": prefs.get("project", {}).get("orientation", "horizontal"),
        "iconStyle": "lucide",
        "iconAnimation": "entrance",
    }


